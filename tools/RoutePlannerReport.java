import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Compares the hand-tuned carry and return routes with A* routes ({@link RoutePlanner}) that keep
 * the same 35 cm clearance, and writes docs/route-planner.md plus docs/images/route-planner.svg.
 *
 * <p>Usage: {@code java RoutePlannerReport worlds/ProjectWorld2025.wbt docs/route-planner.md
 * docs/images/route-planner.svg}
 */
public class RoutePlannerReport {

  /** The hand-tuned routes keep at least this much clearance (RoutesTest checks 30 cm). */
  static final double CLEARANCE_CM = 35;
  /** A cardboard box this close to the clearing route counts as pushed out of the way. */
  static final double SWEEP_CM = 40;
  /** Straight-line driving speed: MAX_SPEED (5 rad/s) x wheel radius (9.75 cm). */
  static final double DRIVE_CM_PER_S = 48.75;

  public static void main(String[] args) throws IOException {
    WorldFile world = WorldFile.read(Path.of(args[0]));

    RoutePlanner noClearing = RoutePlanner.forWorld(world, true, CLEARANCE_CM);
    RoutePlanner afterClearing = RoutePlanner.afterClearing(world, CLEARANCE_CM, SWEEP_CM);
    RoutePlanner staticOnly = RoutePlanner.forWorld(world, false, CLEARANCE_CM);
    List<WorldFile.Obstacle> swept = RoutePlanner.sweptByClearing(world, SWEEP_CM);
    int boxes = world.ofKind(WorldFile.Kind.CARDBOARD_BOX).size();

    Vec2 search = Routes.SEARCH_POINT;
    Vec2 dropoff = Routes.DROPOFF_ENTRY;
    List<Vec2> handCarry = Routes.SEARCH_TO_DROPOFF;
    List<Vec2> handReturn = Routes.DROPOFF_TO_SEARCH.subList(1, Routes.DROPOFF_TO_SEARCH.size());
    List<Vec2> carry = afterClearing.plan(search, dropoff);
    List<Vec2> back = afterClearing.plan(dropoff, search);

    double handCarryCm = Routes.length(search, handCarry);
    double handReturnCm = Routes.length(dropoff, handReturn);
    double carryCm = Routes.length(search, carry);
    double backCm = Routes.length(dropoff, back);
    // A mission carries 5 jars and returns to the search point 4 times.
    double savedCm = 5 * (handCarryCm - carryCm) + 4 * (handReturnCm - backCm);

    StringBuilder md = new StringBuilder();
    md.append("# Route planner: how good are the hand-tuned routes?\n\n");
    md.append("Generated by `tools/RoutePlannerReport.java` (run `tools/run-tests.sh`). **Analysis ")
        .append("only:** neither controller uses the planner.\n\n");
    md.append("Both controllers drive hand-tuned waypoint routes. This compares them with the ")
        .append("shortest routes an A* planner finds on a 5 cm grid built from the world file, ")
        .append("keeping the same ").append(f0(CLEARANCE_CM)).append(" cm clearance from every ")
        .append("obstacle (see `tools/RoutePlanner.java`).\n\n");
    md.append("## Without the box-clearing phase there is no route\n\n");
    md.append("With all ").append(boxes).append(" cardboard boxes where they start, the planner ")
        .append(noClearing.plan(search, dropoff).isEmpty() ? "finds **no route**" : "finds a route")
        .append(" between the search point and the drop-off. That's why the mission begins by ")
        .append("pushing boxes aside along a 15-waypoint route.\n\n");
    md.append("## After clearing\n\n");
    md.append("Here the ").append(swept.size()).append(" cardboard boxes that the clearing route ")
        .append("passes within ").append(f0(SWEEP_CM)).append(" cm of are treated as pushed out ")
        .append("of the way. The other ").append(boxes - swept.size()).append(" stay where they ")
        .append("started, along with the walls and wooden boxes.\n\n");
    md.append("| Route | Hand-tuned (v1 = v2) | A* after clearing | A* with static obstacles only |\n");
    md.append("|---|---|---|---|\n");
    md.append(row("Search point to drop-off (carry)", handCarry.size(), handCarryCm, carry,
        staticOnly.plan(search, dropoff), search));
    md.append(row("Drop-off to search point (return)", handReturn.size(), handReturnCm, back,
        staticOnly.plan(dropoff, search), dropoff));
    md.append("\nThe last column treats every cardboard box as gone, so it's a lower bound.\n\n");
    md.append("**What it means:** the hand-tuned routes are about ")
        .append(f0(100 * (handCarryCm - carryCm) / handCarryCm)).append("% longer than the ")
        .append("planned ones. Over a mission (5 carries, 4 returns) the planned routes would ")
        .append("save about ").append(f0(savedCm / 100)).append(" m, or roughly ")
        .append(f0(savedCm / DRIVE_CM_PER_S)).append(" s of driving at full speed. Turns aren't ")
        .append("counted, but both kinds of route have a similar number of legs. The saving ")
        .append("also assumes the swept boxes really end up clear of the planned line, which ")
        .append("only a Webots run can confirm. So this is a candidate for a future version, ")
        .append("not a change to v2.\n\n");
    md.append("![Map comparing the hand-tuned carry route with the shorter A* route after clearing]")
        .append("(images/route-planner.svg)\n");
    Files.write(Path.of(args[1]), md.toString().getBytes(StandardCharsets.UTF_8));

    Map<String, List<Vec2>> paths = new LinkedHashMap<>();
    paths.put("Hand-tuned carry route (v1 = v2)", withStart(search, handCarry));
    paths.put("A* carry route after clearing", withStart(search, carry));
    String svg = new MapRenderer().renderPaths(world, paths, swept,
        "Hand-tuned vs planned carry route", "Cardboard box the clearing route doesn't reach");
    Files.write(Path.of(args[2]), svg.getBytes(StandardCharsets.UTF_8));
  }

  private static String row(String name, int handLegs, double handCm, List<Vec2> planned,
      List<Vec2> staticPlanned, Vec2 start) {
    return String.format(Locale.ROOT, "| %s | %.1f m, %d legs | %s | %s |%n", name, handCm / 100,
        handLegs, describe(start, planned, handCm), describe(start, staticPlanned, handCm));
  }

  private static String describe(Vec2 start, List<Vec2> route, double handCm) {
    if (route.isEmpty()) {
      return "no route";
    }
    double cm = Routes.length(start, route);
    return String.format(Locale.ROOT, "%.1f m, %d legs (%.0f%% shorter)", cm / 100, route.size(),
        100 * (handCm - cm) / handCm);
  }

  private static List<Vec2> withStart(Vec2 start, List<Vec2> route) {
    List<Vec2> out = new ArrayList<>();
    out.add(start);
    out.addAll(route);
    return out;
  }

  private static String f0(double v) {
    return String.format(Locale.ROOT, "%.0f", v);
  }
}
