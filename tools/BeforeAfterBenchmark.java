import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Measures v1 and v2 algorithms side by side on the same kinematic model and prints a Markdown
 * report (saved as docs/benchmark-results.md by tools/run-tests.sh).
 *
 * <p>The model is an ideal differential-drive robot with the Pioneer 3-DX geometry: no inertia,
 * no wheel slip, no box physics. It isolates the control logic; it is not a Webots substitute.
 */
public class BeforeAfterBenchmark {

  public static void main(String[] args) throws Exception {
    Log.useSink(line -> { });
    Path world = Path.of(args.length > 0 ? args[0] : "worlds/ProjectWorld2025.wbt");
    StringBuilder md = new StringBuilder();
    md.append("# Before/after benchmark (kinematic model)\n\n");
    md.append("Generated by `tools/BeforeAfterBenchmark.java` (run `tools/run-tests.sh`). ")
        .append("v1 numbers come from line-for-line ports of the original methods in ")
        .append("`tests/LegacyV1.java`; v2 numbers run the real v2 classes. Both drive the same ")
        .append("ideal differential-drive model (Pioneer 3-DX wheel radius 9.75 cm, track 33 cm, ")
        .append("32 ms steps). The model has no inertia, slip or box physics, so treat these as ")
        .append("measurements of the control logic, not of the Webots simulation.\n\n");
    md.append("| Check | v1 (before) | v2 (after) |\n|---|---|---|\n");

    turns(md);
    scan(md);
    drift(md);
    blocked(md);
    approach(md);
    failedSearch(md, WorldFile.read(world));
    mission(md, WorldFile.read(world));

    lagSteps = 2;
    turnEfficiency = 0.7;
    md.append("\n## With motor lag and wheel slip\n\n")
        .append("The same checks on a less ideal robot: every wheel command takes effect ")
        .append(lagSteps).append(" steps (").append(lagSteps * 32).append(" ms) late, and turns ")
        .append("achieve only ").append(f0(turnEfficiency * 100)).append("% of the ideal rate. ")
        .append("Neither version was tuned for these numbers.\n\n");
    md.append("| Check | v1 (before) | v2 (after) |\n|---|---|---|\n");
    turns(md);
    scan(md);
    drift(md);
    imperfectMission(md, WorldFile.read(world));

    System.out.print(md);
  }

  /** Imperfections applied to every robot the checks create; 0 / 1.0 = the ideal model. */
  private static int lagSteps = 0;
  private static double turnEfficiency = 1.0;

  private static KinematicRobot robot(Vec2 position, double headingDeg) {
    return new KinematicRobot(position, headingDeg).withImperfections(lagSteps, turnEfficiency);
  }

  private static void imperfectMission(StringBuilder md, WorldFile world) {
    KinematicRobot robot = missionRobot(world);
    Mission mission = new Mission(robot);
    int delivered = mission.run();
    MissionStats s = mission.stats();
    row(md, MISSION_ROW, v1Mission(world),
        delivered + "/5 jars, " + f0(robot.elapsedMs() / 1000.0) + " s simulated, "
            + s.driveStalls() + " stalls, " + s.turnTimeouts() + " turn timeouts");
    md.append("\nWith lag and slip, v1's turns do finish, but each one overshoots: the motors keep ")
        .append("turning for the lag after v1 stops them. v1 drives every leg without steering, so ")
        .append("the error adds up from leg to leg. On the third return trip it is far enough off ")
        .append("its route to drive into an immovable box, and with no stall detection it pushes ")
        .append("against it until the simulation ends. v2 steers on every leg and gives up on a ")
        .append("blocked leg after a few seconds.\n");
  }

  static final String MISSION_ROW =
      "Whole mission (walls and wooden boxes are solid; no box physics)";
  /** v1's whole mission is stopped after this many steps (3,200 s, about 4x v2's mission). */
  static final int V1_MISSION_STEP_LIMIT = 100_000;

  /** The mission's start (see {@link KinematicRobot#atMissionStart}) with the current imperfections. */
  static KinematicRobot missionRobot(WorldFile world) {
    return KinematicRobot.atMissionStart(world).withImperfections(lagSteps, turnEfficiency);
  }

  /** Runs the port of v1's whole mission and describes how it went. */
  static String v1Mission(WorldFile world) {
    KinematicRobot robot = missionRobot(world).withStepLimit(V1_MISSION_STEP_LIMIT);
    LegacyV1Mission.Result r = new LegacyV1Mission(robot, 1).run();
    if (r.finished) {
      return r.delivered + "/5 jars, " + f0(r.elapsedMs / 1000.0) + " s simulated";
    }
    String against = "";
    for (WorldFile.Obstacle o : world.staticObstacles()) {
      if (RoutePlanner.distanceToPolygon(robot.positionCm(), o.corners)
          < KinematicRobot.ROBOT_RADIUS_CM + 1) {
        against = ", blocked by " + o.name;
      }
    }
    return r.delivered + "/5 jars, never finishes: stuck from " + f0(r.activitySinceMs / 1000.0)
        + " s " + r.activity + against + ", still at it when stopped at "
        + f0(r.elapsedMs / 1000.0) + " s";
  }

  /** Every (start, target) heading pair on a grid; does the turn finish, and how fast? */
  private static void turns(StringBuilder md) {
    int pairs = 0;
    int v1Done = 0;
    int v2Done = 0;
    long v1Steps = 0;
    long v2Steps = 0;
    double v1MaxErr = 0;
    double v2MaxErr = 0;
    for (int start = 0; start < 360; start += 3) {
      for (int target = 0; target < 360; target += 7) {
        pairs++;
        double rad = Math.toRadians(target);
        Vec2 goal = Vec2.of(1000 * Math.cos(rad), 1000 * Math.sin(rad));

        KinematicRobot r1 = robot(Vec2.of(0, 0), start);
        int s1 = LegacyV1.makeHardcodedTurn(r1, 0, 0, goal.x, goal.y, 1000);
        if (s1 > 0) {
          v1Done++;
          v1Steps += s1;
          v1MaxErr = Math.max(v1MaxErr, Math.abs(Angles.delta(r1.headingDeg(), Vec2.of(0, 0).bearingTo(goal))));
        }

        KinematicRobot r2 = robot(Vec2.of(0, 0), start);
        Navigator nav = new Navigator(r2, new MissionStats(r2::elapsedMs));
        if (nav.turnTo(Vec2.of(0, 0).bearingTo(goal), Config.MAX_SPEED)) {
          v2Done++;
          v2Steps += r2.stepsTaken();
          v2MaxErr = Math.max(v2MaxErr, Math.abs(Angles.delta(r2.headingDeg(), Vec2.of(0, 0).bearingTo(goal))));
        }
      }
    }
    row(md, "Turn-in-place: finishes within 1000 steps (" + pairs + " start/target pairs)",
        pct(v1Done, pairs), pct(v2Done, pairs));
    row(md, "Turn-in-place: mean steps when it finishes",
        f1(v1Steps / (double) Math.max(1, v1Done)), f1(v2Steps / (double) Math.max(1, v2Done)));
    row(md, "Turn-in-place: worst final heading error when it finishes",
        f1(v1MaxErr) + " deg", f1(v2MaxErr) + " deg");
  }

  private static void scan(StringBuilder md) {
    KinematicRobot r1 = robot(Vec2.of(0, 0), 0);
    LegacyV1.rotateAndFindGreen(r1);
    KinematicRobot r2 = robot(Vec2.of(0, 0), 0);
    handler(r2).scan();
    row(md, "360-degree jar scan: rotation actually covered",
        f0(r1.cumulativeTurnDeg) + " deg", f0(r2.cumulativeTurnDeg) + " deg");

    KinematicRobot b1 = robot(Vec2.of(0, 0), 0);
    b1.jars.add(Vec2.of(100 * Math.cos(Math.toRadians(-45)), 100 * Math.sin(Math.toRadians(-45))));
    KinematicRobot b2 = robot(Vec2.of(0, 0), 0);
    b2.jars.addAll(b1.jars);
    row(md, "Scan finds a jar 1 m away, 45 deg right of the starting heading",
        LegacyV1.rotateAndFindGreen(b1) == null ? "no (blind spot)" : "yes",
        handler(b2).scan() == null ? "no" : "yes");
  }

  /** Longest leg in the routes (530 cm) started 2.9 deg off, which the +/-3 deg turn tolerance allows. */
  private static void drift(StringBuilder md) {
    Vec2 target = Vec2.of(530, 0);
    KinematicRobot r1 = robot(Vec2.of(0, 0), 2.9);
    LegacyV1.moveHardcodedAhead(r1, 0, 0, target.x, target.y, 10_000);
    KinematicRobot r2 = robot(Vec2.of(0, 0), 2.9);
    new Navigator(r2, new MissionStats(r2::elapsedMs)).driveTo(target);
    row(md, "530 cm leg starting 2.9 deg off: distance from waypoint at the end",
        f1(r1.positionCm().distanceTo(target)) + " cm", f1(r2.positionCm().distanceTo(target)) + " cm");
  }

  private static void blocked(StringBuilder md) {
    KinematicRobot r1 = robot(Vec2.of(0, 0), 0);
    r1.blocked = p -> p.x > 100;
    int s1 = LegacyV1.moveHardcodedAhead(r1, 0, 0, 300, 0, 20_000);
    KinematicRobot r2 = robot(Vec2.of(0, 0), 0);
    r2.blocked = p -> p.x > 100;
    Navigator.DriveResult result = new Navigator(r2, new MissionStats(r2::elapsedMs)).driveTo(Vec2.of(300, 0));
    row(md, "Drive blocked by an immovable obstacle after 1 m",
        s1 < 0 ? "never returns (still pushing after 20,000 steps)" : "returns after " + s1 + " steps",
        result + " after " + r2.stepsTaken() + " steps (" + f1(r2.elapsedMs() / 1000.0) + " s)");
  }

  private static void approach(StringBuilder md) {
    double perStepCm = KinematicRobot.WHEEL_RADIUS_CM * LegacyV1.APPROACH_SPEED * 0.032;
    double v1Reach = LegacyV1.APPROACH_EFFECTIVE_STEPS * perStepCm;
    double v2Reach = Config.APPROACH_TIMEOUT_STEPS * perStepCm;
    row(md, "Longest straight approach before the time limit aborts it",
        f0(v1Reach) + " cm (300 steps)", f0(v2Reach) + " cm cap; aborts early only if not moving");

    KinematicRobot r2 = robot(Vec2.of(0, 0), 0);
    r2.jars.add(Vec2.of(150, 0));
    boolean v2Grabbed = handler(r2).approachAndGrab();
    row(md, "Approach and grab a jar 1.5 m ahead in one attempt",
        "no (needs about " + f0((150 - KinematicRobot.TOUCH_DISTANCE_CM) / perStepCm) + " steps)",
        v2Grabbed ? "yes" : "no");
  }

  private static void failedSearch(StringBuilder md, WorldFile world) {
    List<Vec2> v1Route = Routes.DROPOFF_TO_SEARCH; // v1 used this whenever jarsToGo != 5
    double v1Len = Routes.length(Routes.SEARCH_POINT, v1Route);
    double v2Len = Routes.length(Routes.SEARCH_POINT, Routes.TO_SEARCH_POINT);
    List<String> crossed = new ArrayList<>();
    for (WorldFile.Obstacle o : world.staticObstacles()) {
      if (WorldFile.clearance(Routes.SEARCH_POINT, Routes.DROPOFF_ENTRY, o) == 0) {
        crossed.add(o.name);
      }
    }
    row(md, "Route after a failed search for jars 2-5",
        f0(v1Len / 100) + " m; first leg passes through " + crossed.size()
            + " static obstacles (" + String.join(", ", crossed) + ")",
        f1(v2Len / 100) + " m; stays at the search point");
  }

  private static void mission(StringBuilder md, WorldFile world) {
    KinematicRobot robot = missionRobot(world);
    Mission mission = new Mission(robot);
    int delivered = mission.run();
    MissionStats s = mission.stats();
    row(md, MISSION_ROW, v1Mission(world),
        delivered + "/5 jars, " + f0(robot.elapsedMs() / 1000.0) + " s simulated, "
            + s.driveStalls() + " stalls, " + s.turnTimeouts() + " turn timeouts");

    KinematicRobot plannedRobot = missionRobot(world);
    int plannedDelivered = new Mission(plannedRobot, Routes.PLANNED).run();
    row(md, "Whole mission with v2's opt-in A*-planned routes (`Config.USE_PLANNED_ROUTES`)", "-",
        plannedDelivered + "/5 jars, " + f0(plannedRobot.elapsedMs() / 1000.0) + " s simulated");

    KinematicRobot empty = new KinematicRobot(Vec2.of(850, 60), 270).withStepLimit(400_000);
    Mission noJars = new Mission(empty);
    String v2 = "ends after " + noJars.run() + " jars, " + f0(empty.elapsedMs() / 1000.0) + " s";
    row(md, "Mission when no jar can be found",
        "retries forever (by inspection: `while (jarsToGo > 0)` has no attempt limit)", v2);
    md.append("\nThe whole-mission rows run a line-for-line port of v1's `main` loop ")
        .append("(`tests/LegacyV1Mission.java`) and the real v2 classes from the world's start pose, ")
        .append("with the same waypoints and gripper timings (checked by `RoutesTest`). ")
        .append("On the ideal model v1 never gets past the box-clearing route. The 5th leg heads ")
        .append("for 0 deg, and v1 accepts a heading only if its compass reading (0-359) is within 3 deg ")
        .append("of the target without wrapping, so near 0 deg only 0, 1 and 2 count. At full speed ")
        .append("the robot turns about 5.4 deg per step, so it keeps stepping over that window. v2 ")
        .append("compares headings across the 0/360 seam and slows down near the target.\n");
  }

  private static JarHandler handler(KinematicRobot robot) {
    MissionStats stats = new MissionStats(robot::elapsedMs);
    return new JarHandler(robot, new Navigator(robot, stats), stats, new java.util.Random(1));
  }

  private static void row(StringBuilder md, String check, String before, String after) {
    md.append("| ").append(check).append(" | ").append(before).append(" | ").append(after).append(" |\n");
  }

  private static String pct(int n, int of) {
    return String.format(Locale.ROOT, "%.1f%% (%d/%d)", 100.0 * n / of, n, of);
  }

  private static String f0(double v) {
    return String.format(Locale.ROOT, "%.0f", v);
  }

  private static String f1(double v) {
    return String.format(Locale.ROOT, "%.1f", v);
  }
}
