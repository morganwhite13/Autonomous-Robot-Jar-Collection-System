import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;

/**
 * Summarises a robustness sweep (tools/webots-sweep.sh): for each version, how many shuffled
 * worlds it delivered every jar in, plus one row per world.
 *
 * <p>Usage: {@code java WebotsSweepReport build/webots-sweep FIRST LAST LIMIT v1 v2}
 */
public class WebotsSweepReport {

  /**
   * {@code java WebotsSweepReport --compare FIRST LAST LIMIT label=dir:version ...}: one column per
   * sweep, for comparing settings run into separate folders.
   */
  public static void main(String[] args) throws IOException {
    if (args[0].equals("--compare")) {
      int first = Integer.parseInt(args[1]);
      int last = Integer.parseInt(args[2]);
      List<String> labels = new ArrayList<>();
      List<Integer> seeds = new ArrayList<>();
      List<List<WebotsReport.Run>> runs = new ArrayList<>();
      for (int seed = first; seed <= last; seed++) {
        seeds.add(seed);
        runs.add(new ArrayList<>());
      }
      for (int i = 4; i < args.length; i++) {
        String label = args[i].substring(0, args[i].indexOf('='));
        String dir = args[i].substring(args[i].indexOf('=') + 1, args[i].lastIndexOf(':'));
        String version = args[i].substring(args[i].lastIndexOf(':') + 1);
        labels.add(label);
        for (int s = 0; s < seeds.size(); s++) {
          Path runDir = Path.of(dir).resolve("seed-" + seeds.get(s)).resolve(version);
          runs.get(s).add(Files.exists(runDir.resolve("result.properties"))
              ? WebotsReport.load(runDir, version) : null);
        }
      }
      System.out.print(markdown(seeds, labels, runs, args[3]));
      return;
    }
    Path root = Path.of(args[0]);
    int first = Integer.parseInt(args[1]);
    int last = Integer.parseInt(args[2]);
    String limit = args[3];
    List<String> versions = new ArrayList<>();
    for (int i = 4; i < args.length; i++) {
      versions.add(args[i]);
    }
    List<Integer> seeds = new ArrayList<>();
    List<List<WebotsReport.Run>> runs = new ArrayList<>(); // [seed][version], null if missing
    for (int seed = first; seed <= last; seed++) {
      List<WebotsReport.Run> row = new ArrayList<>();
      for (String v : versions) {
        Path dir = root.resolve("seed-" + seed).resolve(v);
        row.add(Files.exists(dir.resolve("result.properties")) ? WebotsReport.load(dir, v) : null);
      }
      seeds.add(seed);
      runs.add(row);
    }
    System.out.print(markdown(seeds, versions, runs, limit));
  }

  static String markdown(List<Integer> seeds, List<String> versions,
      List<List<WebotsReport.Run>> runs, String limit) {
    StringBuilder md = new StringBuilder();
    md.append("# Webots robustness sweep\n\n");
    md.append(String.format(Locale.ROOT, "Generated by `tools/webots-sweep.sh`: each version ran on "
        + "%d shuffled worlds (seeds %d-%d), with a %s s simulated-time limit. Each world places "
        + "the five jars at random in the jar bay and nudges the robot's start pose by up to "
        + "8 cm and 6 degrees (`tools/WorldShuffle.java`). An observer counts a jar once it rests "
        + "in the drop-off lane.\n\n", seeds.size(), seeds.get(0), seeds.get(seeds.size() - 1),
        limit));

    md.append("| |");
    for (String v : versions) {
      md.append(' ').append(v).append(" |");
    }
    md.append("\n|---|");
    for (int i = 0; i < versions.size(); i++) {
      md.append("---|");
    }
    md.append('\n');
    summaryRow(md, versions, runs, "Delivered all 5 jars", (list) -> {
      long all = list.stream().filter(r -> r.delivered() == r.jars() && r.jars() > 0).count();
      return all + " of " + list.size() + " worlds";
    });
    summaryRow(md, versions, runs, "Jars delivered in total", (list) -> {
      int got = 0;
      int of = 0;
      for (WebotsReport.Run r : list) {
        got += r.delivered();
        of += r.jars();
      }
      return got + " of " + of;
    });
    summaryRow(md, versions, runs, "Jars the controller says it delivered", (list) -> {
      long claimed = 0;
      for (WebotsReport.Run r : list) {
        claimed += r.claimed();
      }
      return Long.toString(claimed);
    });
    summaryRow(md, versions, runs, "Mission time when all 5 were delivered (median, range)",
        (list) -> {
          List<Double> times = new ArrayList<>();
          for (WebotsReport.Run r : list) {
            if (r.delivered() == r.jars() && !r.deliveryTimes().isEmpty()) {
              times.add(r.deliveryTimes().get(r.deliveryTimes().size() - 1));
            }
          }
          if (times.isEmpty()) {
            return "-";
          }
          Collections.sort(times);
          return String.format(Locale.ROOT, "%.0f s (%.0f-%.0f s)", median(times), times.get(0),
              times.get(times.size() - 1));
        });
    summaryRow(md, versions, runs, "Runs stuck in one place at the end", (list) -> {
      long stuck = list.stream().filter(r -> !Double.isNaN(r.stuckFromS())).count();
      return Long.toString(stuck);
    });

    md.append("\n## Each world\n\nJars delivered (and, when different, how many the controller "
        + "claimed), then the time the last one was delivered.\n\n| Seed |");
    for (String v : versions) {
      md.append(' ').append(v).append(" |");
    }
    md.append("\n|---|");
    for (int i = 0; i < versions.size(); i++) {
      md.append("---|");
    }
    md.append('\n');
    for (int s = 0; s < seeds.size(); s++) {
      md.append("| ").append(seeds.get(s)).append(" |");
      for (WebotsReport.Run r : runs.get(s)) {
        md.append(' ').append(r == null ? "not run" : cell(r)).append(" |");
      }
      md.append('\n');
    }
    return md.toString();
  }

  private interface Summary {
    String of(List<WebotsReport.Run> runs);
  }

  private static void summaryRow(StringBuilder md, List<String> versions,
      List<List<WebotsReport.Run>> runs, String label, Summary summary) {
    md.append("| ").append(label).append(" |");
    for (int v = 0; v < versions.size(); v++) {
      List<WebotsReport.Run> list = new ArrayList<>();
      for (List<WebotsReport.Run> row : runs) {
        if (row.get(v) != null) {
          list.add(row.get(v));
        }
      }
      md.append(' ').append(list.isEmpty() ? "-" : summary.of(list)).append(" |");
    }
    md.append('\n');
  }

  static String cell(WebotsReport.Run r) {
    StringBuilder s = new StringBuilder(r.delivered() + "/" + r.jars());
    if (r.claimed() != r.delivered()) {
      s.append(" (claimed ").append(r.claimed()).append(')');
    }
    if (r.delivered() == r.jars() && !r.deliveryTimes().isEmpty()) {
      s.append(String.format(Locale.ROOT, ", %.0f s",
          r.deliveryTimes().get(r.deliveryTimes().size() - 1)));
    } else if (!Double.isNaN(r.stuckFromS())) {
      s.append(String.format(Locale.ROOT, ", stuck from %.0f s", r.stuckFromS()));
    }
    return s.toString();
  }

  static double median(List<Double> sorted) {
    int n = sorted.size();
    return n % 2 == 1 ? sorted.get(n / 2) : (sorted.get(n / 2 - 1) + sorted.get(n / 2)) / 2;
  }
}
